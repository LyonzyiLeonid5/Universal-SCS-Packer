#!/usr/bin/env python3
"""Native release builder for Universal SCS Packer.

PyInstaller bundles the Python interpreter for the host operating system.  A
Windows build therefore has to be made on Windows, a DEB/RPM on Linux and a
macOS app on macOS; this script intentionally refuses misleading cross-builds.
"""
from __future__ import annotations

import argparse
import base64
import os
import platform
import secrets
import shutil
import subprocess
import sys
import tarfile
import tempfile
import textwrap
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parent


@dataclass(frozen=True)
class Application:
    key: str
    project: Path
    spec: str
    executable: str
    package: str
    title: str
    identifier: str
    entry: str
    description: str


APPS = {
    "packer": Application(
        "packer", ROOT, "UniversalSCSPacker.spec",
        "UniversalSCSPacker", "universal-scs-packer", "Universal SCS Packer",
        "org.universalscs.packer", "UniversalSCSPacker",
        "Create SCS archives in HashFS, eZIP and AEM formats."),
}


class BuildError(RuntimeError):
    pass


def host_kind() -> str:
    if sys.platform == "win32":
        return "windows"
    if sys.platform == "darwin":
        return "macos"
    if sys.platform.startswith("linux"):
        return "linux"
    raise BuildError(f"Unsupported build host: {platform.platform()}")


def run(command: list[str], *, cwd: Path | None = None,
        env: dict[str, str] | None = None) -> None:
    print("+", " ".join(str(item) for item in command))
    subprocess.run(command, cwd=cwd, env=env, check=True)


def ensure_pyinstaller(python: str, app: Application, skip_install: bool) -> None:
    probe = subprocess.run([python, "-c", "import PyInstaller"],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if probe.returncode == 0:
        return
    if skip_install:
        raise BuildError("PyInstaller is missing and --skip-install was requested.")
    run([python, "-m", "pip", "install", "--upgrade", "-r",
         str(app.project / "requirements-build.txt")])


def _obfuscated_pair(value: str) -> tuple[str, str]:
    key = secrets.token_bytes(32)
    raw = value.encode("utf-8")
    cipher = bytes(byte ^ key[index % len(key)] for index, byte in enumerate(raw))
    return base64.b64encode(cipher).decode("ascii"), base64.b64encode(key).decode("ascii")


def write_community_defaults(app: Application, webhook: str, message_id: str) -> tuple[Path, bytes | None] | None:
    if app.key != "extractor":
        return None
    if bool(webhook) != bool(message_id):
        raise BuildError("--community-webhook and --community-message-id must be provided together.")
    if message_id and not message_id.isdecimal():
        raise BuildError("--community-message-id must contain digits only.")
    target = app.project / "Extractor" / "community_defaults.py"
    previous = target.read_bytes() if target.exists() else None
    webhook_cipher, webhook_key = _obfuscated_pair(webhook)
    message_cipher, message_key = _obfuscated_pair(message_id)
    target.write_text(textwrap.dedent(f"""\
        # Generated by build.py. This is obfuscation, not a security boundary.
        import base64

        def _decode(ciphertext, key):
            data = base64.b64decode(ciphertext)
            key = base64.b64decode(key)
            return bytes(value ^ key[index % len(key)] for index, value in enumerate(data)).decode("utf-8")

        _WEBHOOK = ({webhook_cipher!r}, {webhook_key!r})
        _MESSAGE_ID = ({message_cipher!r}, {message_key!r})

        def load_defaults():
            return _decode(*_WEBHOOK), _decode(*_MESSAGE_ID)
        """), encoding="utf-8")
    return target, previous


def restore_community_defaults(state: tuple[Path, bytes | None] | None) -> None:
    if state is None:
        return
    target, previous = state
    if previous is None:
        target.unlink(missing_ok=True)
    else:
        target.write_bytes(previous)


def make_macos_icon(app: Application, work: Path) -> Path:
    """Make the ICNS required by Finder from the maintained PNG icon."""
    iconset = work / f"{app.executable}.iconset"
    iconset.mkdir(parents=True, exist_ok=True)
    source = app.project / "assets" / "app-icon-256.png"
    for size in (16, 32, 128, 256, 512):
        for scale in (1, 2):
            target = iconset / f"icon_{size}x{size}{'@2x' if scale == 2 else ''}.png"
            run(["sips", "-z", str(size * scale), str(size * scale),
                 str(source), "--out", str(target)])
    icon = work / f"{app.executable}.icns"
    run(["iconutil", "-c", "icns", str(iconset), "-o", str(icon)])
    return icon


def build_binary(app: Application, args: argparse.Namespace, host: str) -> Path:
    ensure_pyinstaller(args.python, app, args.skip_install)
    if app.key == "packer" and host == "windows":
        for relative in ("DirectStorage/dstorage.dll", "DirectStorage/dstoragecore.dll",
                         "ArchiveBackend/7z.exe", "ArchiveBackend/7z.dll"):
            if not (app.project / relative).is_file():
                raise BuildError(f"Missing Windows runtime: {app.project / relative}")
    if app.key == "packer" and not (app.project / "original_game_paths.tar.gz").is_file():
        raise BuildError("Packer path bundle is missing: original_game_paths.tar.gz")

    work = app.project / "build" / "native"
    dist = app.project / "dist"
    environment = os.environ.copy()
    with tempfile.TemporaryDirectory(prefix="universal-scs-build-") as temporary:
        if host == "macos":
            environment["UNIVERSAL_SCS_BUILD_ICON"] = str(make_macos_icon(app, Path(temporary)))
        state = write_community_defaults(app, args.community_webhook,
                                         args.community_message_id)
        try:
            run([args.python, "-m", "PyInstaller", "--clean", "--noconfirm",
                 "--distpath", str(dist), "--workpath", str(work),
                 str(app.project / app.spec)], cwd=app.project, env=environment)
        finally:
            restore_community_defaults(state)
    suffix = ".exe" if host == "windows" else ".app" if host == "macos" else ""
    artifact = dist / f"{app.executable}{suffix}"
    if not artifact.exists():
        raise BuildError(f"PyInstaller completed without {artifact}")
    print(f"Built: {artifact}")
    return artifact


def stage_linux_layout(app: Application, artifact: Path, stage: Path) -> None:
    binary = stage / "usr" / "bin" / app.package
    binary.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(artifact, binary)
    binary.chmod(0o755)
    applications = stage / "usr" / "share" / "applications"
    applications.mkdir(parents=True, exist_ok=True)
    (applications / f"{app.package}.desktop").write_text(textwrap.dedent(f"""\
        [Desktop Entry]
        Type=Application
        Name={app.title}
        Comment={app.description}
        Exec={app.package} %F
        Icon={app.package}
        Terminal=false
        Categories=Utility;
        MimeType=application/x-scs;
        """), encoding="utf-8")
    icon = stage / "usr" / "share" / "icons" / "hicolor" / "256x256" / "apps"
    icon.mkdir(parents=True, exist_ok=True)
    shutil.copy2(app.project / "assets" / "app-icon-256.png", icon / f"{app.package}.png")
    docs = stage / "usr" / "share" / "doc" / app.package
    docs.mkdir(parents=True, exist_ok=True)
    for name in ("README.md", "LICENSE"):
        source = app.project / name
        if source.is_file():
            target = docs / name
            shutil.copy2(source, target)
            target.chmod(0o644)
    if not any(docs.iterdir()):
        (docs / "README.txt").write_text(app.description + "\n", encoding="utf-8")


def deb_architecture() -> str:
    machine = platform.machine().lower()
    return {"x86_64": "amd64", "amd64": "amd64", "aarch64": "arm64"}.get(machine, machine)


def rpm_architecture() -> str:
    machine = platform.machine().lower()
    return {"amd64": "x86_64", "aarch64": "aarch64"}.get(machine, machine)


def build_deb(app: Application, artifact: Path, args: argparse.Namespace) -> Path:
    if shutil.which("dpkg-deb") is None:
        raise BuildError("DEB packaging requires dpkg-deb (run this on Debian/Ubuntu or a compatible Linux host).")
    release = app.project / "dist"
    release.mkdir(parents=True, exist_ok=True)
    output = release / f"{app.package}_{args.version}_{deb_architecture()}.deb"
    with tempfile.TemporaryDirectory(prefix="universal-scs-deb-") as temporary:
        stage = Path(temporary) / app.package
        stage.mkdir()
        stage_linux_layout(app, artifact, stage)
        control = stage / "DEBIAN"
        control.mkdir()
        (control / "control").write_text(textwrap.dedent(f"""\
            Package: {app.package}
            Version: {args.version}
            Section: utils
            Priority: optional
            Architecture: {deb_architecture()}
            Maintainer: Universal SCS Tools
            Description: {app.description}
             Native PyInstaller build for Linux.
            """), encoding="utf-8")
        run(["dpkg-deb", "--build", "--root-owner-group", str(stage), str(output)])
    print(f"Package: {output}")
    return output


def build_rpm(app: Application, artifact: Path, args: argparse.Namespace) -> Path:
    if shutil.which("rpmbuild") is None:
        raise BuildError("RPM packaging requires rpmbuild (run this on Fedora/RHEL/openSUSE or a compatible Linux host).")
    release = app.project / "dist"
    release.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="universal-scs-rpm-") as temporary:
        root = Path(temporary) / "rpmbuild"
        for directory in ("BUILD", "BUILDROOT", "RPMS", "SOURCES", "SPECS", "SRPMS"):
            (root / directory).mkdir(parents=True)
        source_root = Path(temporary) / f"{app.package}-{args.version}"
        stage_linux_layout(app, artifact, source_root)
        tarball = root / "SOURCES" / f"{app.package}-{args.version}.tar.gz"
        with tarfile.open(tarball, "w:gz") as archive:
            archive.add(source_root, arcname=source_root.name)
        spec = root / "SPECS" / f"{app.package}.spec"
        spec.write_text(textwrap.dedent(f"""\
            # PyInstaller stores its embedded application archive after the ELF
            # payload.  RPM's default brp-strip/debug post-processing may alter
            # that finished executable and make it exit before Python starts.
            %global __os_install_post %{{nil}}
            %global debug_package %{{nil}}
            # The extractor and packer use the same PyInstaller bootloader and
            # can consequently receive the same ELF build ID.  Per-package
            # build-id links would then conflict under /usr/lib/.build-id.
            %global _build_id_links none

            Name:           {app.package}
            Version:        {args.version}
            Release:        1%{{?dist}}
            Summary:        {app.description}
            License:        GPL-2.0-only
            Source0:        %{{name}}-%{{version}}.tar.gz
            BuildArch:      {rpm_architecture()}

            %description
            {app.description}

            %prep
            %setup -q

            %install
            rm -rf %{{buildroot}}
            install -D -m 0755 usr/bin/{app.package} %{{buildroot}}/usr/bin/{app.package}
            install -D -m 0644 usr/share/applications/{app.package}.desktop %{{buildroot}}/usr/share/applications/{app.package}.desktop
            install -D -m 0644 usr/share/icons/hicolor/256x256/apps/{app.package}.png %{{buildroot}}/usr/share/icons/hicolor/256x256/apps/{app.package}.png
            install -D -m 0644 usr/share/doc/{app.package}/README.md %{{buildroot}}/usr/share/doc/{app.package}/README.md
            install -D -m 0644 usr/share/doc/{app.package}/LICENSE %{{buildroot}}/usr/share/doc/{app.package}/LICENSE

            %files
            /usr/bin/{app.package}
            /usr/share/applications/{app.package}.desktop
            /usr/share/icons/hicolor/256x256/apps/{app.package}.png
            %doc /usr/share/doc/{app.package}/README.md
            %license /usr/share/doc/{app.package}/LICENSE
            """), encoding="utf-8")
        run(["rpmbuild", "--define", f"_topdir {root}", "-bb", str(spec)])
        results = list((root / "RPMS").rglob("*.rpm"))
        if len(results) != 1:
            raise BuildError("rpmbuild did not produce exactly one RPM package.")
        output = release / results[0].name
        shutil.copy2(results[0], output)
    print(f"Package: {output}")
    return output


def build_macos_zip(app: Application, artifact: Path, args: argparse.Namespace) -> Path:
    release = app.project / "dist"
    release.mkdir(parents=True, exist_ok=True)
    output = release / f"{app.package}-{args.version}-macos.app.zip"
    if shutil.which("ditto") is None:
        raise BuildError("macOS application packaging requires the built-in ditto utility.")
    output.unlink(missing_ok=True)
    run(["ditto", "-c", "-k", "--sequesterRsrc", "--keepParent",
         str(artifact), str(output)])
    if not output.is_file():
        raise BuildError(f"ditto completed without creating {output}")
    # PyInstaller leaves both the bundle and its standalone Mach-O executable
    # in dist. They are intermediate macOS build products; the release artifact
    # is the ZIP which preserves the complete .app bundle.
    if artifact.is_dir():
        shutil.rmtree(artifact)
    elif artifact.exists():
        artifact.unlink()
    standalone = release / app.executable
    if standalone.is_file():
        standalone.unlink()
    print(f"Package: {output}")
    return output


def copy_portable(app: Application, artifact: Path, host: str, args: argparse.Namespace) -> Path:
    release = app.project / "dist"
    release.mkdir(parents=True, exist_ok=True)
    if host == "macos":
        target = release / artifact.name
        if target.resolve() == artifact.resolve():
            print(f"Portable artifact: {artifact}")
            return artifact
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(artifact, target)
    else:
        target = release / artifact.name
        if target.resolve() == artifact.resolve():
            print(f"Portable artifact: {artifact}")
            return artifact
        shutil.copy2(artifact, target)
    print(f"Portable artifact: {target}")
    return target


def formats_for(args: argparse.Namespace, host: str) -> list[str]:
    requested = args.format
    if requested == "auto":
        return {"windows": ["exe"], "linux": ["deb"], "macos": ["app"]}[host]
    if requested == "all":
        return {"windows": ["exe"], "linux": ["deb", "rpm"], "macos": ["app"]}[host]
    allowed = {"windows": {"exe"}, "linux": {"deb", "rpm"}, "macos": {"app"}}[host]
    if requested not in allowed:
        raise BuildError(f"--format {requested} cannot be built on {host}. "
                         "Build native packages on their target operating system.")
    return [requested]


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Build Universal SCS Packer for the current operating system.")
    parser.add_argument("--format", choices=["auto", "all", "exe", "deb", "rpm", "app"], default="auto")
    parser.add_argument("--version", default="1.0.0")
    parser.add_argument("--python", default=sys.executable)
    parser.add_argument("--skip-install", action="store_true")
    parser.set_defaults(community_webhook="", community_message_id="")
    args = parser.parse_args()
    if not args.version or any(char.isspace() for char in args.version):
        raise BuildError("--version must be a non-empty value without whitespace.")
    host = host_kind()
    selected = [APPS["packer"]]
    try:
        for app in selected:
            print(f"\n== {app.title} ({host}) ==")
            artifact = build_binary(app, args, host)
            for package_format in formats_for(args, host):
                if package_format == "exe":
                    copy_portable(app, artifact, host, args)
                elif package_format == "deb":
                    build_deb(app, artifact, args)
                elif package_format == "rpm":
                    build_rpm(app, artifact, args)
                else:
                    build_macos_zip(app, artifact, args)
    except (BuildError, subprocess.CalledProcessError) as exc:
        print(f"Build failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

